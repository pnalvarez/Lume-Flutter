#!/usr/bin/env python3
"""Emit idempotent History trail seed + rollback SQL from a trail dict.

Usage:
  python3 emit_trail_sql.py trail_grecia_roma.py
The trail module must expose TRAIL = {...}.
"""
from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

MIX = {
    "quiz-relampago": 6,
    "verdade-mito": 6,
    "linha-do-tempo": 8,
    "quem-sou-eu": 8,
    "palavra_misteriosa": 6,
    "completar_frase": 6,
    "batalha": 4,
    "conexao": 4,
}


def sql_str(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def sql_json(value) -> str:
    return sql_str(json.dumps(value, ensure_ascii=False))


def correct_answer_for(game_type: str, qd: dict) -> str:
    if game_type == "quiz-relampago":
        return qd["alternativas"][qd["correta"]]
    if game_type == "linha-do-tempo":
        return qd["alternativas"][qd["correta"]]
    if game_type == "verdade-mito":
        return qd["veredito"]
    if game_type == "quem-sou-eu":
        return qd["resposta_certa"]
    if game_type == "palavra_misteriosa":
        return qd["palavra"]
    if game_type == "completar_frase":
        return " | ".join(l["correta"] for l in qd["lacunas"])
    if game_type == "batalha":
        return qd["opcao_a"] if qd["correta"] == "a" else qd["opcao_b"]
    if game_type == "conexao":
        return "; ".join(f"{p['esquerda_id']}->{p['direita_id']}" for p in qd["pares"])
    raise ValueError(game_type)


def prompt_for(game_type: str, qd: dict, hook: str) -> str:
    if game_type == "quiz-relampago":
        return qd["enunciado"]
    if game_type == "linha-do-tempo":
        return qd["situacao_inicial"]
    if game_type == "verdade-mito":
        return qd["texto"]
    if game_type == "quem-sou-eu":
        return qd.get("header") or hook
    if game_type == "palavra_misteriosa":
        return qd["descricao"]
    if game_type == "completar_frase":
        return qd["sentenca"]
    if game_type == "batalha":
        return qd["pergunta"]
    if game_type == "conexao":
        return hook or "Relacione os itens das duas colunas."
    raise ValueError(game_type)


def explicacao_for(game_type: str, qd: dict) -> str:
    if game_type == "conexao":
        # UI shows per-pair text; keep a short fallback for feedback_correct.
        return qd.get("explicacao") or "Cada par liga um conceito ao seu significado histórico."
    return qd["explicacao"]


def content_type_for(game_type: str) -> str:
    if game_type == "linha-do-tempo":
        return "evento"
    if game_type == "conexao":
        return "relacao"
    return "conceito"


def validate(trail: dict) -> None:
    items = trail["items"]
    if len(items) != 48:
        raise SystemExit(f"expected 48 items, got {len(items)}")
    if len(trail["submodules"]) != 12:
        raise SystemExit("expected 12 submodules")
    if len(trail["levels"]) != 4:
        raise SystemExit("expected 4 levels")
    counts = {k: 0 for k in MIX}
    by_sub = {i: 0 for i in range(1, 13)}
    for it in items:
        counts[it["game_type"]] = counts.get(it["game_type"], 0) + 1
        by_sub[it["sub_ordem"]] += 1
        qd = it["question_data"]
        # light structural checks mirroring the validator
        gt = it["game_type"]
        if gt == "quiz-relampago":
            assert isinstance(qd["correta"], int) and 0 <= qd["correta"] < len(qd["alternativas"])
        elif gt == "linha-do-tempo":
            assert isinstance(qd["correta"], int)
        elif gt == "verdade-mito":
            assert qd["veredito"] in ("mito", "verdade", "parcial")
        elif gt == "quem-sou-eu":
            assert sum(1 for i in range(1, 6) if qd.get(f"dica_{i}")) >= 3
        elif gt == "batalha":
            assert qd["correta"] in ("a", "b")
        elif gt == "conexao":
            assert qd.get("titulo") and qd.get("subtitulo")
            assert all(p.get("explicacao") for p in qd["pares"])
    if counts != MIX:
        raise SystemExit(f"mix mismatch: {counts} != {MIX}")
    if any(v != 4 for v in by_sub.values()):
        raise SystemExit(f"each submodule needs 4 pairs: {by_sub}")


def emit_forward(trail: dict) -> str:
    m = trail["module"]
    prefix = trail["slug_prefix"]
    title = m["titulo"]
    lines: list[str] = []
    lines.append(f"-- History pivot / #{trail['issue']}: {title}")
    lines.append(f"-- Generated by generators/emit_trail_sql.py from generators/{trail['source']}.")
    lines.append("-- Idempotent. One transaction. Pair with matching .rollback.sql.")
    lines.append("-- DO NOT apply without owner go-ahead. Dry-run with BEGIN + RAISE EXCEPTION.")
    lines.append("")
    lines.append("BEGIN;")
    lines.append("")
    lines.append("INSERT INTO public.modulos (ordem, titulo, emoji, cor, categoria_id, descricao)")
    lines.append(
        f"SELECT {m['ordem']}, {sql_str(title)}, {sql_str(m['emoji'])}, {sql_str(m['cor'])}, 1, {sql_str(m['descricao'])}"
    )
    lines.append(f"WHERE NOT EXISTS (SELECT 1 FROM public.modulos WHERE titulo = {sql_str(title)});")
    lines.append("")
    lines.append("CREATE TEMP TABLE _seed_trail AS")
    lines.append(f"SELECT id AS modulo_id FROM public.modulos WHERE titulo = {sql_str(title)};")
    lines.append("")
    lines.append("INSERT INTO public.niveis (modulo_id, ordem, titulo)")
    lines.append("SELECT t.modulo_id, v.ordem, v.titulo")
    lines.append("FROM _seed_trail t")
    lines.append("CROSS JOIN (VALUES")
    for i, nivel in enumerate(trail["levels"]):
        comma = "," if i < 3 else ""
        lines.append(f"  ({nivel['ordem']}, {sql_str(nivel['titulo'])}){comma}")
    lines.append(") AS v(ordem, titulo)")
    lines.append("WHERE NOT EXISTS (")
    lines.append("  SELECT 1 FROM public.niveis n WHERE n.modulo_id = t.modulo_id AND n.ordem = v.ordem")
    lines.append(");")
    lines.append("")
    lines.append(
        "INSERT INTO public.submodulos (modulo_id, nivel_id, ordem, titulo, data_liberacao_desde_inicio, imagem_url)"
    )
    lines.append("SELECT t.modulo_id, n.id, v.ordem, v.titulo, 0, NULL")
    lines.append("FROM _seed_trail t")
    lines.append("CROSS JOIN (VALUES")
    for i, sub in enumerate(trail["submodules"]):
        comma = "," if i < 11 else ""
        lines.append(
            f"  ({sub['nivel_ordem']}, {sub['ordem']}, {sql_str(sub['titulo'])}){comma}"
        )
    lines.append(") AS v(nivel_ordem, ordem, titulo)")
    lines.append("JOIN public.niveis n ON n.modulo_id = t.modulo_id AND n.ordem = v.nivel_ordem")
    lines.append("WHERE NOT EXISTS (")
    lines.append("  SELECT 1 FROM public.submodulos s WHERE s.modulo_id = t.modulo_id AND s.ordem = v.ordem")
    lines.append(");")
    lines.append("")
    lines.append("INSERT INTO public.licoes (submodulo_id, ordem, titulo, emoji, conteudo)")
    lines.append("SELECT s.id, 1, s.titulo, " + sql_str(m["emoji"]) + ",")
    lines.append("       jsonb_build_object('preview', v.preview)")
    lines.append("FROM _seed_trail t")
    lines.append("JOIN public.submodulos s ON s.modulo_id = t.modulo_id")
    lines.append("JOIN (VALUES")
    for i, sub in enumerate(trail["submodules"]):
        comma = "," if i < 11 else ""
        lines.append(f"  ({sub['ordem']}, {sql_str(sub['preview'])}){comma}")
    lines.append(") AS v(sub_ordem, preview) ON v.sub_ordem = s.ordem")
    lines.append("WHERE NOT EXISTS (SELECT 1 FROM public.licoes l WHERE l.submodulo_id = s.id);")
    lines.append("")

    # Concepts + items + pairs in one loop
    for idx, it in enumerate(trail["items"], start=1):
        slug = f"{prefix}-{idx:03d}"
        gt = it["game_type"]
        qd = it["question_data"]
        # stamp tipo field used by some existing rows
        tipo_map = {
            "quiz-relampago": "quiz_relampago",
            "verdade-mito": "verdade_mito_parcial",
            "linha-do-tempo": "o_que_aconteceu_depois",
            "quem-sou-eu": "quem_sou_eu",
            "palavra_misteriosa": "palavra_misteriosa",
            "completar_frase": "complete_a_sentenca",
            "batalha": "batalha_curiosidades",
            "conexao": "conexoes",
        }
        qd = {**qd, "tipo": tipo_map[gt]}
        expl = explicacao_for(gt, qd)
        prompt = prompt_for(gt, qd, it["preview_hook"])
        correct = correct_answer_for(gt, qd)
        title_c = f"{it['concept_title']}"
        short = it.get("short_explanation") or expl
        lines.append(f"-- pair {idx}: sub {it['sub_ordem']} / {gt}")
        lines.append("WITH ins AS (")
        lines.append("  INSERT INTO public.concepts (title, slug, short_explanation, full_explanation, difficulty, content_type, status)")
        lines.append(
            f"  SELECT {sql_str(title_c)}, {sql_str(slug)}, {sql_str(short)}, {sql_str(expl)}, 'medio', {sql_str(content_type_for(gt))}, 'active'"
        )
        lines.append(f"  WHERE NOT EXISTS (SELECT 1 FROM public.concepts WHERE slug = {sql_str(slug)})")
        lines.append("  RETURNING id")
        lines.append("), picked AS (")
        lines.append("  SELECT id FROM ins")
        lines.append("  UNION ALL")
        lines.append(
            f"  SELECT id FROM public.concepts WHERE slug = {sql_str(slug)} AND NOT EXISTS (SELECT 1 FROM ins)"
        )
        lines.append("), item AS (")
        lines.append("  INSERT INTO public.concept_game_items (")
        lines.append("    concept_id, game_type, prompt, question_data, correct_answer,")
        lines.append("    feedback_correct, feedback_incorrect, difficulty, active")
        lines.append("  )")
        lines.append(
            f"  SELECT p.id, {sql_str(gt)}, {sql_str(prompt)}, {sql_json(qd)}::jsonb, {sql_str(correct)},"
        )
        lines.append(
            f"         {sql_str(expl)}, 'Revise o conceito e tente de novo.', 'medio', true"
        )
        lines.append("  FROM picked p")
        lines.append("  WHERE NOT EXISTS (")
        lines.append(
            f"    SELECT 1 FROM public.concept_game_items cgi WHERE cgi.concept_id = p.id AND cgi.game_type = {sql_str(gt)}"
        )
        lines.append("  )")
        lines.append("  RETURNING concept_id")
        lines.append(")")
        lines.append("INSERT INTO public.submodulo_pares (")
        lines.append("  submodulo_id, ordem, preview_hook, game_type, content_type,")
        lines.append("  cognitive_demand, concept_id, licao_id")
        lines.append(")")
        lines.append(
            f"SELECT s.id, {it['pair_ordem']}, {sql_str(it['preview_hook'])}, {sql_str(gt)}, {sql_str(content_type_for(gt))},"
        )
        lines.append(
            f"       {sql_str(it.get('cognitive_demand', 'media'))}, p.id, l.id"
        )
        lines.append("FROM picked p")
        lines.append("JOIN _seed_trail t ON true")
        lines.append(
            f"JOIN public.submodulos s ON s.modulo_id = t.modulo_id AND s.ordem = {it['sub_ordem']}"
        )
        lines.append("JOIN public.licoes l ON l.submodulo_id = s.id")
        lines.append("WHERE NOT EXISTS (")
        lines.append(
            f"  SELECT 1 FROM public.submodulo_pares sp WHERE sp.submodulo_id = s.id AND sp.ordem = {it['pair_ordem']}"
        )
        lines.append(");")
        lines.append("")

    lines.append("DO $$")
    lines.append("DECLARE")
    lines.append("  v_mod bigint; v_subs int; v_pairs int;")
    lines.append("BEGIN")
    lines.append("  SELECT modulo_id INTO v_mod FROM _seed_trail;")
    lines.append("  SELECT count(*) INTO v_subs FROM public.submodulos WHERE modulo_id = v_mod;")
    lines.append("  SELECT count(*) INTO v_pairs FROM public.submodulo_pares sp")
    lines.append("    JOIN public.submodulos s ON s.id = sp.submodulo_id WHERE s.modulo_id = v_mod;")
    lines.append("  IF v_subs <> 12 OR v_pairs <> 48 THEN")
    lines.append("    RAISE EXCEPTION 'trail seed incomplete: submodules=%, pairs=% (want 12/48)', v_subs, v_pairs;")
    lines.append("  END IF;")
    lines.append("END $$;")
    lines.append("")
    lines.append("DROP TABLE _seed_trail;")
    lines.append("COMMIT;")
    lines.append("")
    return "\n".join(lines)


def emit_rollback(trail: dict) -> str:
    prefix = trail["slug_prefix"]
    title = trail["module"]["titulo"]
    lines = [
        f"-- Rollback for #{trail['issue']}: {title}",
        f"-- Removes only rows created by this trail (slug prefix {prefix}-).",
        "",
        "BEGIN;",
        "",
        "DELETE FROM public.submodulo_pares sp",
        "USING public.submodulos s, public.modulos m",
        "WHERE sp.submodulo_id = s.id",
        "  AND s.modulo_id = m.id",
        f"  AND m.titulo = {sql_str(title)};",
        "",
        "DELETE FROM public.concept_game_items cgi",
        "USING public.concepts c",
        "WHERE cgi.concept_id = c.id",
        f"  AND c.slug LIKE {sql_str(prefix + '-%')};",
        "",
        "DELETE FROM public.concepts",
        f"WHERE slug LIKE {sql_str(prefix + '-%')};",
        "",
        "DELETE FROM public.licoes l",
        "USING public.submodulos s, public.modulos m",
        "WHERE l.submodulo_id = s.id AND s.modulo_id = m.id",
        f"  AND m.titulo = {sql_str(title)};",
        "",
        "DELETE FROM public.submodulos s",
        "USING public.modulos m",
        "WHERE s.modulo_id = m.id",
        f"  AND m.titulo = {sql_str(title)};",
        "",
        "DELETE FROM public.niveis n",
        "USING public.modulos m",
        "WHERE n.modulo_id = m.id",
        f"  AND m.titulo = {sql_str(title)};",
        "",
        "DELETE FROM public.modulos",
        f"WHERE titulo = {sql_str(title)};",
        "",
        "COMMIT;",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: emit_trail_sql.py <trail_module.py>")
    path = Path(sys.argv[1]).resolve()
    spec = importlib.util.spec_from_file_location("trail_mod", path)
    mod = importlib.util.module_from_spec(spec)
    assert spec.loader
    spec.loader.exec_module(mod)
    trail = mod.TRAIL
    trail["source"] = path.name
    validate(trail)

    out_dir = path.parent.parent
    num = trail["file_num"]
    slug = trail["file_slug"]
    forward = out_dir / f"{num}_trail_{slug}.sql"
    rollback = out_dir / f"{num}_trail_{slug}.rollback.sql"
    forward.write_text(emit_forward(trail), encoding="utf-8")
    rollback.write_text(emit_rollback(trail), encoding="utf-8")
    print(f"wrote {forward.name} and {rollback.name}")


if __name__ == "__main__":
    main()
